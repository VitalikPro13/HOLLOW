/// Start the libp2p node with mDNS peer discovery and E2EE.
/// Uses the persistent identity from disk.
/// Returns the local peer ID as a string.
#[frb]
pub fn start_node() -> Result<String, String> {
    let node = get_node();
    let mut guard = node.lock().map_err(|e| format!("Lock poisoned: {e}"))?;

    if guard.is_some() {
        return Err("Node is already running".to_string());
    }

    // Wait for any in-progress background fetch to finish (up to 5s).
    for _ in 0..50 {
        if !FETCH_ACTIVE.load(Ordering::SeqCst) {
            break;
        }
        std::thread::sleep(std::time::Duration::from_millis(100));
    }

    // Initialize debug log file (writes next to executable, works in release builds).
    crate::log::init();
    hollow_log!("[HOLLOW] === Node starting ===");

    // Load the persistent identity (or create one if first run).
    let id = identity::load_or_create_identity()?;

    // Derive the DB encryption key (same as storage module).
    let proto = id
        .keypair
        .to_protobuf_encoding()
        .map_err(|e| format!("Failed to encode keypair: {e}"))?;
    let key_bytes = &proto[..32.min(proto.len())];
    let passphrase = hex::encode(key_bytes);

    // Get DB path.
    let hollow_dir = crate::identity::data_dir()?;
    std::fs::create_dir_all(&hollow_dir)
        .map_err(|e| format!("Failed to create data dir: {e}"))?;
    let db_path = hollow_dir
        .join("messages.db")
        .to_str()
        .ok_or("Invalid path encoding")?
        .to_string();

    // One-time storage hygiene (legacy `auto_vacuum=0` → INCREMENTAL). MUST run
    // HERE — this is the single-connection window: it precedes the first
    // MessageStore::open below AND the CryptoStore/CrdtStore actors (opened later
    // in their own blocking threads). Doing the VACUUM/page-1 probe while those
    // long-lived connections are open raced the SQLCipher codec and logged
    // `hmac check failed for pgno=1`. Non-fatal: pure disk hygiene.
    if let Err(e) = MessageStore::migrate_auto_vacuum_once(&db_path, &passphrase) {
        hollow_log!("[HOLLOW] auto_vacuum migration skipped: {e}");
    }

    // Load Olm state from DB (synchronous, on FFI thread).
    let olm = {
        let store = MessageStore::open(&db_path, &passphrase)?;
        // Seed the Lamport chat clock from the highest stored send stamp so a
        // restart can't mint stamps below messages we already hold (see
        // chat_clock.rs — cross-machine ordering fix).
        crate::chat_clock::observe(store.max_chat_stamp_us());
        match store.load_olm_account()? {
            Some(account_json) => {
                let sessions = store.load_all_olm_sessions()?;
                OlmManager::from_pickles(&account_json, sessions)?
            }
            None => {
                // First time — create fresh Olm account and persist it.
                let mgr = OlmManager::new();
                let pickle = mgr.account_pickle_json()?;
                store.save_olm_account(&pickle)?;
                mgr
            }
        }
    };

    // Extract fingerprint before moving OlmManager into the swarm task.
    let olm_fingerprint = olm.identity_key_base64();

    // Load invisible mode preference from DB so the node starts invisible
    // before any peers connect (avoids a brief "online" flash on restart).
    let initial_invisible = {
        let store = MessageStore::open(&db_path, &passphrase)?;
        let raw = store.load_setting("invisible_mode");
        hollow_log!("[HOLLOW-STATUS] Loaded invisible_mode from DB: {:?}", raw);
        raw.ok()
            .flatten()
            .map(|v| v == "true")
            .unwrap_or(false)
    };
    hollow_log!("[HOLLOW-STATUS] initial_invisible = {initial_invisible}");

    // Open the CryptoStore persistence actor (runs in its own blocking thread).
    let rt = get_runtime();
    let crypto_store = rt.block_on(async {
        CryptoStore::open(db_path.clone(), passphrase.clone())
    })?;

    // Open the CrdtStore persistence actor (batched CRDT state writes).
    let crdt_store = rt.block_on(async {
        CrdtStore::open(db_path, passphrase)
    })?;

    let license_key = get_license_key()
        .lock()
        .map_err(|e| format!("Lock poisoned: {e}"))?
        .clone();

    let relay_domain = get_relay_domain()
        .lock()
        .map_err(|e| format!("Lock poisoned: {e}"))?
        .clone()
        .unwrap_or_else(|| "relay.anonlisten.com".to_string());

    // Anti-censorship proxy: if a REALITY config is set, launch the local
    // `shoes` tunnel and publish its SOCKS5 address so ws_client routes the
    // relay connection through it. A tunnel-launch failure does NOT block node
    // startup — we log it and fall back to a direct connection (which is what
    // the user was doing before), so a bad proxy config never bricks the app.
    {
        // Kill any shoes orphaned by a prior run (hard restart / crash) BEFORE
        // deciding to launch — runs whether the proxy is now on or off, so a
        // stale tunnel never lingers after the user turns the proxy off.
        node::proxy_tunnel::sweep_orphan();

        let cfg = get_proxy_config()
            .lock()
            .map_err(|e| format!("Lock poisoned: {e}"))?
            .clone();
        match cfg {
            Some(cfg) => {
                hollow_log!("[HOLLOW-PROXY] Proxy config present (server {}) — launching tunnel", cfg.server);
                match node::proxy_tunnel::start(&cfg) {
                    Ok(addr) => set_proxy_socks_addr(Some(addr)),
                    Err(e) => {
                        hollow_log!("[HOLLOW-PROXY] Tunnel failed to start ({e}); connecting directly");
                        set_proxy_socks_addr(None);
                    }
                }
            }
            None => {
                hollow_log!("[HOLLOW-PROXY] No proxy config set — connecting directly");
                set_proxy_socks_addr(None);
            }
        }
    }

    let (event_tx, event_rx) = mpsc::channel::<node::NetworkEvent>(100);
    let (cmd_tx, cmd_rx) = mpsc::channel::<node::NodeCommand>(100);

    let cmd_tx_clone = cmd_tx.clone();
    let (peer_id_str, handle) = rt
        .block_on(node::spawn_node(id.keypair, id.device_keypair, event_tx, cmd_rx, cmd_tx_clone, olm, crypto_store, crdt_store, license_key, initial_invisible, relay_domain))
        .map_err(|e| format!("Failed to start node: {e}"))?;

    // Store event receiver separately so watch_network_events() can take it.
    *get_event_rx().lock().map_err(|e| format!("Lock poisoned: {e}"))? = Some(event_rx);

    *guard = Some(NodeState {
        local_peer_id: peer_id_str.clone(),
        cmd_tx,
        handle,
        olm_fingerprint,
    });

    Ok(peer_id_str)
}

/// Stream network events to Dart in real time.
/// Must be called after `start_node()`. Can only be called once per node lifetime.
#[frb]
pub fn watch_network_events(sink: StreamSink<NetworkEvent>) -> Result<(), String> {
    let rx = get_event_rx()
        .lock()
        .map_err(|e| format!("Lock poisoned: {e}"))?
        .take()
        .ok_or("No event receiver available (node not started or stream already active)")?;

    let rt = get_runtime();
    rt.spawn(async move {
        event_forwarding_task(rx, sink).await;
    });

    Ok(())
}

async fn event_forwarding_task(
    mut rx: mpsc::Receiver<node::NetworkEvent>,
    sink: StreamSink<NetworkEvent>,
) {
    while let Some(event) = rx.recv().await {
        let ffi_event = to_ffi_event(event);
        if sink.add(ffi_event).is_err() {
            hollow_log!("[HOLLOW] Event stream sink closed, stopping forwarding");
            break;
        }
    }
    hollow_log!("[HOLLOW] Event channel closed, stream ending");
}

/// Poll for the next network event. Returns None if no event is available.
/// Fallback for when streaming is not active.
#[frb]
pub fn poll_network_event() -> Option<NetworkEvent> {
    let rx_lock = get_event_rx();
    let mut guard = rx_lock.lock().ok()?;
    let rx = guard.as_mut()?;
    rx.try_recv().ok().map(to_ffi_event)
}

