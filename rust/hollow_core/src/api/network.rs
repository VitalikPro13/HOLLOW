/// Start a lightweight invisible fetch node to receive buffered messages.
///
/// DM wake (`server_room` = None): joins only the DM room for sender_peer_id
/// and decrypts via Olm. Channel wake (`server_room` = Some(server_id)): joins
/// the server room and decrypts buffered channel messages via MLS (or reads
/// signed public-channel plaintext).
/// Cannot run while the full node is active. Blocks the calling thread.
#[frb]
pub fn start_fetch_node(
    sender_peer_id: String,
    timeout_secs: u32,
    server_room: Option<String>,
) -> Result<Vec<FetchedMessage>, String> {
    if FETCH_ACTIVE.swap(true, Ordering::SeqCst) {
        return Err("Fetch already in progress".to_string());
    }

    // Ensure cleanup on all exit paths.
    struct FetchGuard;
    impl Drop for FetchGuard {
        fn drop(&mut self) {
            FETCH_ACTIVE.store(false, Ordering::SeqCst);
        }
    }
    let _guard = FetchGuard;

    // Cannot run concurrently with full node.
    {
        let node = get_node();
        let node_guard = node.lock().map_err(|e| format!("Lock poisoned: {e}"))?;
        if node_guard.is_some() {
            return Err("Full node is running — cannot start fetch node".to_string());
        }
    }

    crate::log::init();
    hollow_log!("[HOLLOW-FETCH] Starting fetch node for sender {sender_peer_id}");

    // Existing identity only — generating one here would connect with the wrong
    // peer_id and decrypt with the wrong keys.
    let id = match identity::load_existing_identity()? {
        Some(id) => id,
        None => {
            hollow_log!("[HOLLOW-FETCH] No identity file — cannot fetch, returning empty");
            return Ok(vec![]);
        }
    };
    // DB passphrase is derived from the MASTER key (master-derived, must NOT
    // change — a device-derived passphrase would open an empty DB).
    let master_proto = id
        .keypair
        .to_protobuf_encoding()
        .map_err(|e| format!("Failed to encode keypair: {e}"))?;
    let passphrase = hex::encode(&master_proto[..32.min(master_proto.len())]);

    // WS auth uses the DEVICE key: the relay keyed this device's push token +
    // offline buffer by its device id (the full node auths with the device key
    // too), so the fetch MUST auth as the device to receive its buffered
    // ciphertext (the relay replays only to the exact device id that joins).
    let proto = id
        .device_keypair
        .to_protobuf_encoding()
        .map_err(|e| format!("Failed to encode device keypair: {e}"))?;

    let hollow_dir = crate::identity::data_dir()?;
    std::fs::create_dir_all(&hollow_dir)
        .map_err(|e| format!("Failed to create data dir: {e}"))?;
    let db_path = hollow_dir
        .join("messages.db")
        .to_str()
        .ok_or("Invalid path encoding")?
        .to_string();

    // Load Olm state from DB.
    let mut olm = {
        let store = MessageStore::open(&db_path, &passphrase)?;
        match store.load_olm_account()? {
            Some(account_json) => {
                let sessions = store.load_all_olm_sessions()?;
                OlmManager::from_pickles(&account_json, sessions)?
            }
            None => {
                hollow_log!("[HOLLOW-FETCH] No Olm account — cannot decrypt, returning empty");
                return Ok(vec![]);
            }
        }
    };

    use base64::Engine;
    // Device-keyed WS auth (see the proto note above).
    let pub_key_b64 = base64::engine::general_purpose::STANDARD.encode(
        id.device_keypair.public_key_protobuf(),
    );
    let peer_id = id.device_keypair.peer_id();
    let local_master = id.keypair.peer_id();

    // Warm the resolver from persisted device links so run_fetch can map the
    // local device + the sender's device id back to their masters for the
    // MASTER-paired DM room + conversation key (single-device → self-map no-op).
    if let Ok(store) = MessageStore::open(&db_path, &passphrase) {
        if let Ok(links) = store.get_all_device_links() {
            node::resolver::warm_from_links(&links);
        }
    }
    // Ensure our own device→master mapping exists even if no links row yet.
    node::resolver::seed_self(&local_master, &[peer_id.clone(), local_master.clone()]);

    let license_key = get_license_key()
        .lock()
        .map_err(|e| format!("Lock poisoned: {e}"))?
        .clone();
    let relay_domain = get_relay_domain()
        .lock()
        .map_err(|e| format!("Lock poisoned: {e}"))?
        .clone()
        .unwrap_or_else(|| "relay.anonlisten.com".to_string());

    // Channel wake: load the MLS group state for the one server so buffered
    // group ciphertext can be decrypted. A missing/unrestorable MLS identity
    // degrades gracefully (content-free banner; the app syncs on next open).
    let mut mls: Option<crate::crypto::MlsManager> = match server_room {
        Some(ref room) => {
            let store = MessageStore::open(&db_path, &passphrase)?;
            match store.load_mls_identity() {
                Ok(Some((signer, cred, storage))) => {
                    // Restore the server-wide group PLUS every restricted-channel
                    // subgroup (Option B) so a buffered restricted-channel message
                    // can be decrypted. The fetch node has no live ServerState, so
                    // read the persisted state JSON to enumerate subgroup channels.
                    let mut group_keys: Vec<String> = vec![room.clone()];
                    if let Ok(Some(state_json)) = store.load_server_state(room) {
                        if let Ok(state) = serde_json::from_str::<crate::crdt::server_state::ServerState>(&state_json) {
                            for cid in state.subgroup_channel_ids() {
                                group_keys.push(crate::crypto::subgroup_id(room, &cid));
                            }
                        }
                    }
                    match crate::crypto::MlsManager::from_persisted(
                        &signer, &cred, storage.as_deref(), &group_keys,
                    ) {
                        Ok(m) => Some(m),
                        Err(e) => {
                            hollow_log!("[HOLLOW-FETCH] MLS restore failed: {e} — content-free fallback");
                            None
                        }
                    }
                }
                _ => None,
            }
        }
        None => None,
    };

    // Open CryptoStore for session persistence.
    let rt = get_runtime();
    let crypto_store = rt.block_on(async {
        CryptoStore::open(db_path.clone(), passphrase.clone())
    })?;

    let timeout = std::time::Duration::from_secs(timeout_secs as u64);

    let results = rt.block_on(node::fetch::run_fetch(
        &relay_domain,
        &peer_id,
        &local_master,
        &proto,
        &pub_key_b64,
        license_key.as_deref(),
        &sender_peer_id,
        server_room.as_deref(),
        timeout,
        &mut olm,
        &mut mls,
        &crypto_store,
        &db_path,
        &passphrase,
    ))?;

    // Persist final Olm account state (one-time keys may have been consumed).
    if let Ok(account_json) = olm.account_pickle_json() {
        crypto_store.save_account(account_json);
    }

    hollow_log!("[HOLLOW-FETCH] Fetch complete, {} messages", results.len());

    Ok(results
        .into_iter()
        .map(|dm| FetchedMessage {
            from_peer: dm.from_peer,
            text: dm.text,
            timestamp: dm.timestamp,
            message_id: dm.message_id,
            image_path: dm.image_path,
            server_id: dm.server_id,
            channel_id: dm.channel_id,
        })
        .collect())
}

