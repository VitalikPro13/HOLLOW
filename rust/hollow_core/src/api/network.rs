/// Stop the running node.
#[frb]
pub fn stop_node() -> Result<(), String> {
    let node = get_node();
    let mut guard = node.lock().map_err(|e| format!("Lock poisoned: {e}"))?;

    // Clear any unconsumed event receiver.
    if let Ok(mut rx_guard) = get_event_rx().lock() {
        *rx_guard = None;
    }

    // Kill the REALITY proxy tunnel subprocess (if running) and clear its addr
    // so a subsequent restart re-evaluates the proxy config cleanly.
    node::proxy_tunnel::stop();
    set_proxy_socks_addr(None);

    match guard.take() {
        Some(state) => {
            state.handle.abort();
            Ok(())
        }
        None => Err("Node is not running".to_string()),
    }
}

